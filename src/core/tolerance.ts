// koyu — 許容値の族 (ADR-0040)
//
// **同じ問いに二つの許容値があってはならない。**
//
// これらの数は「どれだけ違えば別のものか」を決める。値がモジュールごとに置かれていた
// あいだ、`poly.ts` の EPS と `graph.ts` の EPS は同じ 0.5 を別々に持ち、`vertical.ts` は
// 1 を四箇所に直値で書き、`drawnShare` は軸平行の判定に graph の EPS ではなく直値の 0.5 を
// 使っていた。どれも同じ値なので事故は起きていないが、**一つを動かしたときに何が動くのかを
// 誰も言えない**状態だった。許容値は導出の規則の一部であり (spec/derivation.md §6)、
// 規則が消費者ごとに違えば同じ原本から違う建物が出る。
//
// 座標は mm の整数が基本である。だから長さの許容は 0.5mm — 「これより細かい差は同一」の線が、
// 整数の刻みの半分に置かれている。面積の許容 1mm² は 1mm×1mm の破片であり、
// 半平面で切った残りがこれ以下なら形として数えない。

/** 長さ・座標の許容 mm。辺の共線・向かい合わせ・区間の一致・共線マージの隙間 */
export const EPS = 0.5;

/** 面積の退化の閾値 mm²。切った残りがこれ以下なら空、左右の面積差がこれ未満なら偏りなし */
export const AREA_EPS = 1;

/**
 * 描かれた線の左右を探る距離 mm。**形の解像度の下限である** —
 * この幅を下回る空間は左右のどちらにも判定できず、境界の線分が一本も出ない
 */
export const PROBE = 5;

/**
 * 区間・切断・枠の一致の許容 mm。切断面と部品の z の比較、可視区間の長さの下限、
 * 上る走りと下りる走りが同じ枠かの判定、外皮の穴の長さの下限
 */
export const SPAN_EPS = 1;

/** 半平面で切るときの符号の許容 (単位は外積 = 面積の二倍)。頂点を残すか、交点を挿むか */
export const CROSS_EPS = 1e-6;

/** 無限直線と線分の平行判定・線分側パラメータの範囲の許容 (無次元) */
export const PARALLEL_EPS = 1e-9;

/** 点が多角形の辺の上にあるとみなす幅 mm (境界上は内側扱い) */
export const POINT_EPS = 1;

/**
 * 許容値の台帳。**spec/derivation.md §6 の表の唯一の出所である** —
 * `test/derive.test.ts` が表とここの一致を縛る。
 */
export const TOLERANCES: Readonly<Record<string, number>> = {
  EPS,
  AREA_EPS,
  PROBE,
  SPAN_EPS,
  CROSS_EPS,
  PARALLEL_EPS,
  POINT_EPS,
};
